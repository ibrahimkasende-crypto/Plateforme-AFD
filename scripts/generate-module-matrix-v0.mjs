function flags(statut) {
  const base = {
    navigation: true,
    page: true,
    table_supabase: false,
    relations: false,
    service_serveur: false,
    types: false,
    zod: false,
    liste: false,
    recherche: false,
    filtres: false,
    pagination: false,
    creation: false,
    consultation: false,
    modification: false,
    suppression: false,
    archivage: false,
    restauration: false,
    publication: false,
    workflow: false,
    pieces_jointes: false,
    rls: false,
    permissions: true,
    journalisation: false,
    statistiques: false,
    tests_unitaires: false,
    tests_e2e: false,
    responsive: true,
    accessibilite: false,
  };
  if (
    ["fonctionnel_non_teste", "operationnel", "partiel", "bloque_integration_externe"].includes(
      statut,
    )
  ) {
    Object.assign(base, {
      liste: true,
      service_serveur: true,
      table_supabase: true,
    });
  }
  if (statut === "fonctionnel_non_teste" || statut === "operationnel") {
    Object.assign(base, {
      creation: true,
      modification: true,
      consultation: true,
      zod: true,
      recherche: true,
      filtres: true,
      rls: true,
      tests_e2e: true,
    });
  }
  if (statut === "maquette_seulement") {
    Object.assign(base, {
      liste: false,
      table_supabase: false,
      service_serveur: false,
    });
  }
  if (statut === "bloque_integration_externe") {
    Object.assign(base, {
      liste: true,
      creation: true,
      rls: true,
    });
  }
  return base;
}

